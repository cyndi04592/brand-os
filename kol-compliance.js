  //   ⚠️ 不是用來「排除規則」—— 化粧品商品照樣受化粧品法管,禁詞一個都不能少。
  function isProductForm(prod) {
    if (!prod) return false;
    const yes = String(prod.hasPackaging || '').trim().toLowerCase();
    if (yes === '是' || yes === 'y' || yes === 'yes' || yes === 'true' || yes === '有') return true;
    if (String(prod.packShape || '').trim()) return true;
    const t = String(prod.productType || '').trim().toLowerCase();
    return t === 'packaged' || /包裝|packaged/.test(t);
  }

