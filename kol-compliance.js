  // 產生要併進 kolTabooWords 的字串
  function tabooFor(prod) {
    const key = resolveRule(prod);
    if (!key) return '';
    return RULES[key].words.join('、');
  }

  // 產生要附加在 outline 後面的合規說明(給 AI 看的行為準則)
  function briefFor(prod) {
    const key = resolveRule(prod);
    if (!key) return '';
    const r = RULES[key];
    // 🆕 v1.1:同一套禁詞,但如果它是有包裝的商品,說明改用商品版口吻
    const body = (r.extraProduct && isProductForm(prod)) ? r.extraProduct : r.extra;
    return '\n\n【合規要求 · ' + r.note + '】\n' +
           '以下字詞一律不可出現在任何台詞中:' + r.words.join('、') + '\n' +
           body;
  }

  // 事後檢查:台詞裡有沒有漏網的禁詞(AI 有時會不聽話)
  function scanLines(lines, prod) {
    const key = resolveRule(prod);
    if (!key) return [];
    const words = RULES[key].words;
    const hits = [];
    (Array.isArray(lines) ? lines : [lines]).forEach(function (ln, i) {
      const t = String(ln || '');
      words.forEach(function (w) {
        if (t.includes(w)) hits.push({ index: i, word: w, line: t });
      });
    });
    return hits;
  }

  window.KolCompliance = { RULES, resolveRule, tabooFor, briefFor, scanLines, isProductForm, version: 'v1.2' };
