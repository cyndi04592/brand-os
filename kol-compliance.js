      if (/塔羅|八字|紫微|占卜|命理|風水/.test(hay))            return 'mystic';
      if (/旅遊|行程|導遊|旅行社|一日遊|自由行/.test(hay))       return 'travel';
      if (/水晶|串珠|能量手環|按摩|經絡|保健/.test(hay))         return 'wellness';
      // 🆕 v1.1 行銷代操要排在專業服務之前,否則「品牌顧問」會被 pro 先攔走
